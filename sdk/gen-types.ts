// Generates sdk/commands.gen.ts from Tandem's edit batch JSON schema.
//
//   bun sdk/gen-types.ts <project.tandem | schema.json>
//
// With a project it reads GET /v1/schema from the server that has it open
// (starting `tandem serve` if nothing does). Regenerate after Tandem adds or
// changes an edit command.

import { Tandem } from "./tandem";

type Schema = Record<string, any>;

const arg = process.argv[2];
if (!arg) {
  console.error("Usage: bun sdk/gen-types.ts <project.tandem | schema.json>");
  process.exit(2);
}

let schema: Schema;
if (arg.endsWith(".json")) {
  schema = await Bun.file(arg).json();
} else {
  const t = await Tandem.open(arg);
  try {
    schema = await t.schema();
  } finally {
    await t.close();
  }
}

// Patch targets the schema names but doesn't define.
const patchTypes: Record<string, string> = {
  Project: "Patch<{ name: string; metadata: Record<string, unknown> }>",
  ProjectSettings: "Patch<Record<string, unknown>>",
  Track: "Patch<TrackFields>",
  TransitionPatch:
    "Patch<Pick<Transition, \"type\" | \"direction\" | \"duration\" | \"soundClipID\">> & { sound?: TransitionSound | null }",
};

function doc(s: Schema, indent: string): string {
  if (!s.description) return "";
  return `${indent}/** ${String(s.description).replace(/\*\//g, "* /")} */\n`;
}

function key(k: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
}

function ts(s: Schema, indent = ""): string {
  if (s.$ref) return s.$ref.split("/").pop();
  if (s["x-tandem-patch"]) {
    const name = s["x-tandem-patch"];
    return patchTypes[name] ?? `Patch<${name}>`;
  }
  const alts = s.oneOf ?? s.anyOf;
  if (alts) return alts.map((a: Schema) => ts(a, indent)).join(" | ");
  if (s.enum) return s.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
  const type = Array.isArray(s.type) ? s.type : [s.type];
  return type
    .map((t: string) => {
      switch (t) {
        case "string":
          return "string";
        case "number":
        case "integer":
          return "number";
        case "boolean":
          return "boolean";
        case "null":
          return "null";
        case "array":
          return `Array<${s.items ? ts(s.items, indent) : "unknown"}>`;
        case "object":
        case undefined: {
          const props = s.properties ?? {};
          const names = Object.keys(props);
          if (names.length === 0) {
            if (s.additionalProperties && typeof s.additionalProperties === "object")
              return `Record<string, ${ts(s.additionalProperties, indent)}>`;
            return s.additionalProperties === false ? "Record<string, never>" : "Record<string, unknown>";
          }
          const req = new Set(s.required ?? []);
          const inner = indent + "  ";
          const lines = names.map(
            (n) => `${doc(props[n], inner)}${inner}${key(n)}${req.has(n) ? "" : "?"}: ${ts(props[n], inner)};`,
          );
          return `{\n${lines.join("\n")}\n${indent}}`;
        }
        default:
          return "unknown";
      }
    })
    .join(" | ");
}

const out: string[] = [
  "// Generated by sdk/gen-types.ts from Tandem's /v1/schema. Don't edit by hand.",
  "/* eslint-disable */",
  'import type { Patch, TrackFields } from "./types";',
  "",
];

for (const [name, def] of Object.entries<Schema>(schema.$defs ?? {})) {
  out.push(`${doc(def, "")}export type ${name} = ${ts(def)};`, "");
}

// The sound object addTransition takes, reused by updateTransition's patch.
const commands: Schema[] = schema.properties.commands.items.oneOf;
const addTransition = commands.find((c) => c.properties?.addTransition);
out.push(
  `export type TransitionSound = ${ts(addTransition!.properties.addTransition.properties.sound)};`,
  "",
);

const names: string[] = [];
for (const c of commands) {
  const name = Object.keys(c.properties)[0];
  names.push(name);
  const typeName = name[0].toUpperCase() + name.slice(1);
  out.push(`${doc(c, "")}export type ${typeName}Args = ${ts(c.properties[name])};`, "");
}

out.push("export interface CommandArgs {");
for (const n of names) out.push(`  ${n}: ${n[0].toUpperCase() + n.slice(1)}Args;`);
out.push("}", "");
out.push("export type CommandName = keyof CommandArgs;");
out.push("/** One edit command: an object with exactly one key, the command's name. */");
out.push("export type Command = { [K in CommandName]: { [P in K]: CommandArgs[P] } }[CommandName];");
out.push("");
out.push(`export const commandNames = ${JSON.stringify(names)} as const;`);
out.push("");

const target = new URL("./commands.gen.ts", import.meta.url).pathname;
await Bun.write(target, out.join("\n"));
console.log(`Wrote ${target}: ${names.length} commands, ${Object.keys(schema.$defs ?? {}).length} types.`);
